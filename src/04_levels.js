
/* =====================================================================
   6. LEVEL CHUNKS  -  handcrafted screen-sized segments.
      Legend:  .  empty          #  earth (auto grass)   S  stone        W  house wall   R  roof
               =  wood platform (one-way)   B  bridge (one-way)   C  crumbling plank   ^  spikes
               P  player start   k  checkpoint spot    T  torii goal    s  scroll spot
               p  random power-up   1-5  specific power-up (Flame, Wind, Shield, Thunder, Time Bell)
               e  soldier   a  archer   c  crow   (E A Y = optional soldier/archer/crow, more likely on later levels;
                                                    once unlocked, some become Shield Guards, Frogs, Ninjas or Spooks)
               g  shield guard   n  shadow ninja   w  lantern spook   f  bandit frog
               o  spirit lantern   L  swinging log anchor   t  cherry tree   l  stone lantern   H  house (decor)
               G  boss arena gate   O  boss
      Rules: the first 3 columns must be flat floor (entry), the last column must have floor (exit).
      Entry/exit heights are detected automatically, so climbs simply exit higher than they enter.
   ===================================================================== */
const CHUNK_DEFS = [];
function chunk(id, diff, type, feat, rows) {
  const r = rows.trim().split('\n').map(s => s.trim());
  CHUNK_DEFS.push({ id, diff, type, feat, rows: r });
}
