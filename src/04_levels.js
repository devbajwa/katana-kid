/* =====================================================================
   7. LEVEL GENERATOR  -  seeded by region + level, so a level is always identical.
   ===================================================================== */
const CHUNKS = {};
for (const c of CHUNK_DEFS) {
  const w = Math.max(...c.rows.map(r => r.length)), h = c.rows.length;
  c.rows = c.rows.map(r => r.padEnd(w, '.'));
  if (c.type === 'climb') {   // solid earth under the exit ledge of a climb (right of the shaft wall)
    const g = c.rows.map(r => r.split(''));
    let wall = w - 1; while (wall > 0 && !g.some(r => r[wall] === 'S')) wall--;
    for (let x = wall + 1; x < w; x++) { let y = 0; while (y < h && g[y][x] !== '#') y++; for (; y < h; y++) g[y][x] = '#'; }
    c.rows = g.map(r => r.join(''));
  }
  c.w = w; c.h = h;
  const solidCh = ch => '#SWR=BC^'.indexOf(ch) >= 0;
  const topSolid = x => { for (let y = 0; y < h; y++) if (solidCh(c.rows[y][x])) return y; return h - 1; };
  c.inRow = topSolid(0); c.outRow = topSolid(w - 1);
  CHUNKS[c.id] = c;
}

function generateLevel(regionId, levelNum, mode) {
  const region = REGIONS.find(r => r.id === regionId);
  const rng = mulberry32(hashSeed(regionId * 1000 + levelNum, 0x5a3c));
  const LC = CONFIG.level;
  const unlocked = new Set(['basic']);
  for (let i = 0; i < Math.min(levelNum, 9); i++) unlocked.add(region.intro[i].feat);
  const EU = CONFIG.enemies.unlockLevel;
  for (const k in EU) if (levelNum >= EU[k]) unlocked.add(k);
  // optional spots may turn into a newer enemy; hashed from the position so rng() (and the layout) stays the same
  const variant = (base, gx, gy) => {
    const V = CONFIG.enemies.variants[base], r = hashSeed(gx, gy, levelNum, 77) % 100;
    if (V) for (const v of V) if (unlocked.has(v[0]) && r < v[1]) return v[0];
    return base;
  };
  const newFeat = region.intro[levelNum - 1].feat;
  const usable = c => c.feat.every(f => unlocked.has(f));
  const list = [];
  if (levelNum === 10) {
    list.push(CHUNKS.start, CHUNKS.e_meadow, CHUNKS.rest_garden, CHUNKS.boss_gate, CHUNKS.boss_arena);
  } else {
    const count = LC.chunksBase + Math.round(levelNum * LC.chunksPerLevel);
    const weight = c => {
      if (!usable(c)) return 0;
      if (c.type === 'rest') return 0.5;
      if (c.diff === 1) return levelNum <= 3 ? 3 : levelNum <= 6 ? 1 : 0.35;
      if (c.diff === 2) return levelNum < 2 ? 0 : levelNum <= 3 ? 1.2 : 3;
      return levelNum < 5 ? 0 : levelNum - 3.5;
    };
    let bag = [];
    const pick = () => {
      if (!bag.length) bag = region.chunks.map(id => CHUNKS[id]).filter(c => weight(c) > 0);
      let total = 0; for (const c of bag) total += weight(c);
      let r = rng() * total;
      for (let i = 0; i < bag.length; i++) { r -= weight(bag[i]); if (r <= 0 || i === bag.length - 1) { const c = bag[i]; bag.splice(i, 1); return c; } }
    };
    const body = [];
    // the new idea of this level appears early so its hint makes sense
    const intro = region.chunks.map(id => CHUNKS[id]).filter(c => usable(c) && c.feat.includes(newFeat));
    if (intro.length) { const c = intro[(rng() * intro.length) | 0]; body.push(c); }
    while (body.length < count) {
      const c = pick();
      if (body.length && body[body.length - 1].id === c.id) continue;
      if (body.includes(c) && bag.length) continue;
      body.push(c);
    }
    // keep the intro chunk early but not first
    if (intro.length && body.length > 2) { const c = body.shift(); body.splice(1, 0, c); }
    list.push(CHUNKS.start, ...body, CHUNKS.goal);
  }

  // ---- place chunks: align each chunk's entry floor with the previous exit floor ----
  const placed = [];
  let cx = 0, floorRow = 0;
  for (const c of list) {
    const top = floorRow - c.inRow;
    placed.push({ c, x: cx, y: top });
    cx += c.w; floorRow = top + c.outRow;
  }
  let minY = Infinity, maxY = -Infinity;
  for (const p of placed) { minY = Math.min(minY, p.y); maxY = Math.max(maxY, p.y + p.c.h); }
  const offY = LC.skyRows - minY;
  for (const p of placed) p.y += offY;
  const w = cx, h = maxY + offY + LC.groundRows;
  const L = {
    regionId, levelNum, w, h, tiles: new Uint8Array(w * h), vis: new Uint8Array(w * h), crumbleT: new Float32Array(w * h),
    killY: new Float32Array(w), spawns: [], scrollSpots: [], checkpoints: [], decor: [], lanterns: [], logs: [],
    start: null, goal: null, bossSpawn: null, arena: null, gateCells: [], hint: null, chunkStarts: [],
  };
  const set = (x, y, t) => { if (x >= 0 && y >= 0 && x < w && y < h) L.tiles[y * w + x] = t; };
  const optionalChance = LC.optionalEnemyBase + LC.optionalEnemyPerLevel * levelNum;
  const powerPool = CONFIG.powers.unlockByLevel[Math.min(levelNum, CONFIG.powers.unlockByLevel.length) - 1];
  placed.forEach((p, ci) => {
    const c = p.c;
    L.chunkStarts.push({ x: p.x, floorY: p.y + c.inRow, id: c.id });
    for (let y = 0; y < c.h; y++) for (let x = 0; x < c.w; x++) {
      const ch = c.rows[y][x], gx = p.x + x, gy = p.y + y, px = gx * TS + TS / 2, py = gy * TS + TS; // py = bottom of cell
      switch (ch) {
        case '#': set(gx, gy, TILE.GROUND); break;
        case 'S': set(gx, gy, TILE.STONE); break;
        case 'W': set(gx, gy, TILE.WALL); break;
        case 'R': set(gx, gy, TILE.ROOF); break;
        case '=': set(gx, gy, TILE.PLAT); break;
        case 'B': set(gx, gy, TILE.BRIDGE); break;
        case 'C': set(gx, gy, TILE.CRUMBLE); break;
        case '^': set(gx, gy, TILE.SPIKE); break;
        case 'P': L.start = { x: px, y: py }; break;
        case 'T': L.goal = { x: px, y: py }; break;
        case 'k': L.checkpoints.push({ x: px, y: py, lit: false, fixed: true }); break;
        case 's': L.scrollSpots.push({ x: px, y: py - 8, chunk: ci }); break;
        case 'p': if (powerPool.length) L.spawns.push({ kind: 'orb', x: px, y: py - 8, ptype: powerPool[(rng() * powerPool.length) | 0] }); break;
        case '1': case '2': case '3': case '4': case '5': L.spawns.push({ kind: 'orb', x: px, y: py - 8, ptype: +ch - 1 }); break;
        case 'e': L.spawns.push({ kind: 'soldier', x: px, y: py }); break;
        case 'a': L.spawns.push({ kind: 'archer', x: px, y: py }); break;
        case 'c': L.spawns.push({ kind: 'crow', x: px, y: py - 8 }); break;
        case 'g': L.spawns.push({ kind: 'shield', x: px, y: py }); break;
        case 'n': L.spawns.push({ kind: 'ninja', x: px, y: py }); break;
        case 'w': L.spawns.push({ kind: 'wisp', x: px, y: py - 8 }); break;
        case 'f': L.spawns.push({ kind: 'frog', x: px, y: py }); break;
        case 'E': if (rng() < optionalChance) { const k = variant('soldier', gx, gy); L.spawns.push({ kind: k, x: px, y: py }); } break;
        case 'A': if (unlocked.has('archer') && rng() < optionalChance) L.spawns.push({ kind: variant('archer', gx, gy), x: px, y: py }); break;
        case 'Y': if (unlocked.has('crow') && rng() < optionalChance) { const k = variant('crow', gx, gy); L.spawns.push({ kind: k, x: px, y: py - 8 }); } break;
        case 'o': L.lanterns.push({ x: px, y: py - 10, hitT: 0, bob: rng() * 6 }); break;
        case 'L': L.logs.push({ ax: px, ay: gy * TS + 8, len: 0, phase: rng() * 6.28 }); break;
        case 't': L.decor.push({ img: 'tree', x: px, y: py, back: true }); break;
        case 'l': L.decor.push({ img: 'lantern', x: px, y: py, back: true }); break;
        case 'H': L.decor.push({ img: 'house', x: px, y: py, back: true }); break;
        case 'G': L.gateCells.push(gy * w + gx); break;
        case 'O': L.bossSpawn = { x: px, y: py }; L.arena = { x0: (p.x + 3) * TS, x1: (p.x + c.w) * TS, y0: p.y * TS, y1: (p.y + c.h) * TS, trigger: (p.x + 8) * TS }; break;
      }
    }
    // extend ground below the chunk; record fall-out depth per column
    for (let x = 0; x < c.w; x++) {
      const gx = p.x + x, bottom = p.y + c.h - 1, t = L.tiles[bottom * w + gx];
      if (SOLID[t]) for (let y = bottom + 1; y < h; y++) set(gx, y, t === TILE.SPIKE ? TILE.GROUND : t);
      L.killY[gx] = (p.y + c.h) * TS + LC.killDepth;
    }
  });
  // checkpoints: two per level, at the start of chunks one third and two thirds through
  {
    const n = placed.length;
    for (const idx of [Math.max(1, Math.round(n / 3)), Math.max(2, Math.round(2 * n / 3))]) {
      if (L.checkpoints.length >= 2) break;
      const p = placed[Math.min(idx, n - 2)];
      if (L.checkpoints.some(k => Math.abs(k.x - (p.x + 1) * TS) < TS * 4)) continue;
      L.checkpoints.push({ x: (p.x + 1) * TS + TS / 2, y: (p.y + p.c.inRow) * TS, lit: false });
    }
  }
  L.checkpoints.sort((a, b) => a.x - b.x);
  // three hidden scrolls, preferring different chunks
  const spots = L.scrollSpots.slice();
  for (let i = spots.length - 1; i > 0; i--) { const j = (rng() * (i + 1)) | 0; [spots[i], spots[j]] = [spots[j], spots[i]]; }
  const chosen = [], used = new Set();
  for (const s of spots) if (chosen.length < 3 && !used.has(s.chunk)) { chosen.push(s); used.add(s.chunk); }
  for (const s of spots) if (chosen.length < 3 && !chosen.includes(s)) chosen.push(s);
  chosen.sort((a, b) => a.x - b.x);
  chosen.forEach((s, i) => L.spawns.push({ kind: 'scroll', x: s.x, y: s.y, idx: i }));
  // swinging logs hang down to just above the floor below them
  for (const lg of L.logs) {
    const tx = Math.floor(lg.ax / TS); let ty = Math.floor(lg.ay / TS) + 1;
    while (ty < h && !SOLID[L.tiles[ty * w + tx]] && !ONEWAY[L.tiles[ty * w + tx]]) ty++;
    lg.len = ty * TS - lg.ay - 20;
  }
  if (L.goal) L.goal = { x: L.goal.x, y: L.goal.y };
  buildVisuals(L, rng);
  L.hint = region.intro[levelNum - 1];
  L.isBoss = !!L.bossSpawn;
  return L;
}
function tileAt(L, x, y) { return x < 0 || x >= L.w ? TILE.STONE : y < 0 || y >= L.h ? TILE.EMPTY : L.tiles[y * L.w + x]; }
function buildVisuals(L, rng) {
  const { w, h, tiles, vis } = L;
  const solidish = (x, y) => { const t = tileAt(L, x, y); return t === TILE.GROUND || t === TILE.STONE || t === TILE.WALL || t === TILE.ROOF || t === TILE.SPIKE; };
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const t = tiles[y * w + x]; let v = 0;
    const f = (solidish(x, y - 1) ? 0 : 1) | (solidish(x - 1, y) ? 0 : 2) | (solidish(x + 1, y) ? 0 : 4) | (solidish(x, y + 1) ? 0 : 8);
    if (t === TILE.GROUND) v = TV.GROUND + f;
    else if (t === TILE.STONE) v = TV.STONE + f;
    else if (t === TILE.WALL) v = ((x * 7 + y * 3) % 3 === 0) ? TV.WALLWIN : TV.WALL;
    else if (t === TILE.ROOF) v = tileAt(L, x, y - 1) === TILE.ROOF ? TV.ROOF : TV.ROOFTOP;
    else if (t === TILE.PLAT) v = TV.PLAT;
    else if (t === TILE.BRIDGE) v = TV.BRIDGE;
    else if (t === TILE.CRUMBLE) v = TV.CRUMBLE;
    else if (t === TILE.SPIKE) v = TV.SPIKE;
    vis[y * w + x] = v;
    // grass tufts and flowers on exposed earth
    if (t === TILE.GROUND && (f & 1) && tileAt(L, x, y - 1) === TILE.EMPTY) {
      const r = rng();
      if (r < 0.38) L.decor.push({ img: 'grass', x: x * TS + 2 + ((rng() * 4) | 0), y: y * TS, phase: (rng() * 4) | 0 });
      else if (r < 0.46) L.decor.push({ img: 'flowers', x: x * TS + 3, y: y * TS });
    }
  }
}
